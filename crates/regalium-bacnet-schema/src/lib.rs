//! The `BACnet` domain model, generated from the protobuf source of truth.
//!
//! `protobuf/` is the authority for what a device, object, point and event
//! are, shaped to Google AIP. Three artefacts come out of it and this crate
//! carries all three:
//!
//! - **prost types** for the configuration surface, where a few hundred
//!   nanoseconds of parsing never mattered;
//! - **`FlatBuffers` and Cap’n Proto mirrors** of the hot-path payloads — COV
//!   notifications, readings, event notifications — derived by `buffers` from
//!   the same descriptor set, never hand-written. The schemas and their
//!   ledger are in `protobuf/generated/` (`just gen-mirror`); Rust bindings
//!   join this crate when a consumer needs zero-copy reads;
//! - the **module wiring** that makes them reachable, which is hand-written
//!   because `buffers` emits no `mod.rs` for Rust.
//!
//! # The resources
//!
//! | Resource | Name | Backed by |
//! | --- | --- | --- |
//! | [`device::Device`] | `devices/599` | the Device object (§12.11); found by `Who-Is` (§16.10) |
//! | [`object::Object`] | `devices/599/objects/analog-input-1` | one object (Clause 12): `CreateObject`, `DeleteObject`, `WritePropertyMultiple` |
//! | [`object::Property`] | `…/properties/present-value` | `ReadProperty`, `ReadPropertyMultiple`, `WriteProperty` |
//! | [`object::Subscription`] | `…/subscriptions/{subscription}` | `SubscribeCOV` and `SubscribeCOVProperty` (Clause 13) |
//!
//! `BACnet` enumerations that vendors may extend — object types, property
//! identifiers, units, event states, error codes — are strings in the
//! standard's own spelling (`analog-input`, `present-value`), with `type-N`
//! for a value this build cannot name. An enum could carry neither a
//! proprietary value nor the standard's zero, which protobuf reserves.
//!
//! The services are declared, not served: [`device`] and [`object`] carry
//! the messages, and transport is a later decision. [`convert`] fills them
//! from what the core decodes — an I-Am becomes a [`device::Device`], a
//! `ReadProperty-ACK` an [`object::Property`] — and turns a property's name
//! back into the `ReadProperty` that gets it.
//!
//! # Concurrency
//!
//! Every type is plain data: `Send`, `Sync`, and safe to share.
//!
//! # Why the core does not import this
//!
//! The protocol layers do not depend on the generated types. Doing so would
//! put prost in the dependency graph of every consumer of the codec, and the
//! codec's whole value is that it has no graph. Conversion lives here and
//! imports the core, not the other way round.
//!
//! # Ordinals are a wire format
//!
//! `buffers.lock` records the target slot every field was assigned. A
//! consumer compiled when a field sat at ordinal 5 reads slot 5 forever, and
//! no compiler in the chain reports it when a rebuild puts something else
//! there. `just gen all` fails on a moved ordinal rather than shipping it.
//!
//! # Layer contract
//!
//! Owns: generated types and the conversions between them and the core's
//! protocol types.
//!
//! Must not: appear in the dependency graph of the core or any datalink.
//!
//! Allowed imports: `regalium-bacnet-core`, `regalium-bacnet-telemetry`.

